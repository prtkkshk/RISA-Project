def lit(v):
    if v is None or (isinstance(v, float) and pd.isna(v)) or v is pd.NaT: return "null"
    if isinstance(v, (bool,)): return "true" if v else "false"
    if isinstance(v, pd.Timestamp): return "'" + v.strftime("%Y-%m-%dT%H:%M:%S") + "+05:30'"
    if isinstance(v, (int,)) or (hasattr(v, "dtype") and "int" in str(getattr(v, "dtype", ""))): return str(int(v))
    if isinstance(v, float): return str(int(v)) if v.is_integer() else str(v)
    return "'" + str(v).replace("'", "''") + "'"

def dump(table, df, cols=None):
    cols = cols or list(df.columns)
    out = []
    for _, r in df.iterrows():
        out.append("(" + ",".join(lit(r[c] if not hasattr(r[c], 'item') else r[c].item() if not isinstance(r[c], pd.Timestamp) else r[c]) for c in cols) + ")")
    print(f"insert into {table} ({','.join(cols)}) values\n" + ",\n".join(out) + ";\n")

